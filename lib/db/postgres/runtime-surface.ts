export type PostgresSourceMethod=keyof typeof POSTGRES_SOURCE_METHOD_ACCESS;
export interface PostgresSourceSurface {readonly mainnet:boolean;readonly readOnly:boolean;readonly privacyActive:boolean;readonly claimsEnabled:boolean;readonly publicProfilesActive:boolean;}
export function assertPostgresSourceMethodAccess(name:PostgresSourceMethod,surface:PostgresSourceSurface){
 if(!Object.hasOwn(POSTGRES_SOURCE_METHOD_ACCESS,name))refuseStorage('invalid_operation');
 const access=POSTGRES_SOURCE_METHOD_ACCESS[name];
 if(access.startsWith('mainnet-')&&!surface.mainnet)refuseStorage('invalid_operation');
 if(surface.readOnly&&(access==='write'||access==='mainnet-write'||name==='assertResearchPurchaseAuthority'))refuseStorage('readonly_operation');
 return access;
}
