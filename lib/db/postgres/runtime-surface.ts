export function postgresSourcePropertyEnabled(name:keyof typeof POSTGRES_SOURCE_PROPERTIES,s:PostgresSourceSurface){
 switch(POSTGRES_SOURCE_PROPERTIES[name]){
  case 'always':return true;case 'mainnet':return s.mainnet;case 'claims':return s.claimsEnabled;case 'ownership':return s.privacyActive||s.claimsEnabled;
  case 'privacy':return s.privacyActive;case 'public-profiles':return s.mainnet&&s.privacyActive&&s.publicProfilesActive;
  case 'readonly-privacy':return s.mainnet&&s.readOnly&&s.privacyActive;
 }
}
