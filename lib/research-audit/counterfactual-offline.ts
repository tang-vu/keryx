import { z } from "zod";
import { boundedPortableCopy } from "../research/bounded-portable-json";
import { outcomeIdentifier } from "../research/purchase-outcomes-contract";
import { planCounterfactualSample } from "./counterfactual-allowance";

/** Fixed offline limits. Quote allowance is a sampling bound, never money or signing authority. */
export const OFFLINE_COUNTERFACTUAL_POLICY = Object.freeze({
  version: "retained-skip-literal-v1" as const,
  sampleLimit: 8,
  quotedAllowanceMicros: "20000",
  maximumInputBytes: 1024 * 1024,
  maximumBodyBytes: 512 * 1024,
  maximumClaims: 64,
  seed: "issue298-retained-skip-literal-v1",
});
const digest = z.string().regex(/^[a-f0-9]{64}$/);
const identity = { sourceId: outcomeIdentifier, itemId: outcomeIdentifier, contentVersion: outcomeIdentifier };
const time = z.string().datetime({ offset: true }).max(64);
const claim = z.object({ id: outcomeIdentifier, literal: z.string().min(1).max(2048).refine(value => !!value.trim()) }).strict();
const inputSchema = z.object({
  schemaVersion: z.literal("keryx-offline-counterfactual-input-v1"),
  run: z.object({ id: outcomeIdentifier, completedAt: time,
    answer: z.string().min(1).max(500_000).refine(value => !!value.trim()),
    decisions: z.array(z.object({ sourceId: outcomeIdentifier, itemId: outcomeIdentifier.optional(),
      contentVersion: outcomeIdentifier.optional(), action: z.enum(["BUY", "SKIP", "CACHE"]),
      price: z.number().finite().nonnegative(), external: z.boolean().optional() }).strict()).max(512),
    // Conservative exclusions from retained reads, access payments or citations, including gap
    // purchases whose initial decision still says SKIP. Producer provenance is reviewed separately.
    observedReads: z.array(z.object(identity).strict()).max(512),
  }).strict(),
  // The reference is supplied independently of the runner, never generated by this evaluator.
  // Its digest binds the retained literals; neither the digest nor the label attests their truth.
  reference: z.object({ claims: z.array(claim).min(1).max(OFFLINE_COUNTERFACTUAL_POLICY.maximumClaims), sha256: digest }).strict(),
  snapshots: z.array(z.object({ ...identity, body: z.string().max(OFFLINE_COUNTERFACTUAL_POLICY.maximumBodyBytes),
    bodySha256: digest, capturedAt: time }).strict()).max(512),
}).strict();
export type OfflineCounterfactualInput = z.infer<typeof inputSchema>;

export async function sha256Text(text: string): Promise<string> {
  const bytes = new TextEncoder().encode(text);
  const hash = await globalThis.crypto.subtle.digest("SHA-256", bytes);
  return [...new Uint8Array(hash)].map(byte => byte.toString(16).padStart(2, "0")).join("");
}
const keyOf = (value: { sourceId: string; itemId: string; contentVersion: string }) =>
  JSON.stringify([value.sourceId, value.itemId, value.contentVersion]);

/**
 * Read a bounded sample AFTER a completed run from hash-checked retained bodies only.
 * There is deliberately no reader callback, environment, URL, wallet, user budget,
 * reward sink, provider or model capability. Missing bodies stay missing; no fallback.
 *
 * The measured outcome is a missing reference literal found in a retained skipped body.
 * It is not semantic usefulness, entailment, expert review or population missed value.
 */
export async function evaluateRetainedSkips(value: unknown) {
  // Copy before the first await so callers cannot replace identities, content or quotes mid-run.
  const input = inputSchema.parse(boundedPortableCopy(value, OFFLINE_COUNTERFACTUAL_POLICY.maximumInputBytes));
  const referenceHash = await sha256Text(JSON.stringify(input.reference.claims));
  if (referenceHash !== input.reference.sha256) throw new Error("Counterfactual reference digest refused");
  const ids = new Set<string>(), literals = new Set<string>();
  for (const row of input.reference.claims) {
    if (ids.has(row.id) || literals.has(row.literal)) throw new Error("Ambiguous counterfactual reference");
    ids.add(row.id); literals.add(row.literal);
  }
  const snapshots = new Map<string, typeof input.snapshots[number]>();
  let bodyBytes = 0;
  for (const row of input.snapshots) {
    bodyBytes += new TextEncoder().encode(row.body).length;
    if (bodyBytes > OFFLINE_COUNTERFACTUAL_POLICY.maximumBodyBytes) throw new Error("Counterfactual body allowance exceeded");
    const key = keyOf(row);
    if (snapshots.has(key)) throw new Error("Repeated counterfactual snapshot identity");
    if (Date.parse(row.capturedAt) < Date.parse(input.run.completedAt)) throw new Error("Counterfactual snapshot predates completion");
    if (await sha256Text(row.body) !== row.bodySha256) throw new Error("Counterfactual body digest refused");
    snapshots.set(key, row);
  }
  const alreadyRead = new Set(input.run.observedReads.map(keyOf));
  const decisions = input.run.decisions.filter(row => !(row.itemId && row.contentVersion
    && alreadyRead.has(keyOf({ sourceId: row.sourceId, itemId: row.itemId, contentVersion: row.contentVersion }))));
  const plan = await planCounterfactualSample({ runId: input.run.id, seed: OFFLINE_COUNTERFACTUAL_POLICY.seed,
    decisions, allowanceMicros: OFFLINE_COUNTERFACTUAL_POLICY.quotedAllowanceMicros,
    sampleLimit: OFFLINE_COUNTERFACTUAL_POLICY.sampleLimit });
  const missing = input.reference.claims.filter(row => !input.run.answer.includes(row.literal));
  const found = new Set<string>();
  const reads = plan.sample.map(row => {
    const snapshot = snapshots.get(keyOf(row));
    const foundClaims = snapshot ? missing.filter(claim => snapshot.body.includes(claim.literal)).map(claim => claim.id) : [];
    foundClaims.forEach(id => found.add(id));
    return { ...row, status: snapshot ? "retained-body-read" as const : "retained-body-missing" as const,
      bodySha256: snapshot?.bodySha256 ?? null, capturedAt: snapshot?.capturedAt ?? null, foundClaimIds: foundClaims };
  });
  const readCount = reads.filter(row => row.status === "retained-body-read").length;
  return {
    schemaVersion: "keryx-offline-counterfactual-result-v1" as const,
    runId: input.run.id, completedAt: input.run.completedAt,
    policy: { ...OFFLINE_COUNTERFACTUAL_POLICY },
    inputSha256: await sha256Text(JSON.stringify(input)), referenceSha256: referenceHash,
    eligibleSkips: plan.eligibleSkips, sampledSkips: reads.length,
    excludedObservedReadDecisions: input.run.decisions.length - decisions.length,
    omittedForQuoteAllowance: plan.omittedForAllowance, plannedQuoteMicros: plan.plannedMicros,
    retainedBodyReads: readCount, unavailableBodies: reads.length - readCount,
    referenceClaims: input.reference.claims.length, missingReferenceClaims: missing.length,
    foundMissingClaimIds: missing.filter(row => found.has(row.id)).map(row => row.id),
    // A missing body makes the selected-sample rate unknown, rather than a zero-value skip.
    sampledLiteralMissRate: !reads.length || readCount !== reads.length ? null :
      reads.filter(row => row.foundClaimIds.length > 0).length / reads.length,
    reads,
    basis: "exact reference literals absent from answer and present in retained skipped bodies" as const,
    coverage: "selected offline sample only; literal occurrence is not semantic support" as const,
    funding: "none-offline-retained-content" as const, actualSpendMicros: "0" as const,
    rewardEligible: false as const,
  };
}
